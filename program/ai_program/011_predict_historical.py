# ===========================================================
# モデル読込
# ===========================================================

def load_model():

    log(
        "======================================="
    )

    log(
        "Model Load"
    )

    log(
        "======================================="
    )

    if not MODEL_FILE.exists():

        raise FileNotFoundError(
            MODEL_FILE
        )

    if not FEATURE_FILE.exists():

        raise FileNotFoundError(
            FEATURE_FILE
        )

    model = joblib.load(

        MODEL_FILE,

    )

    with open(

        FEATURE_FILE,

        "r",

        encoding="utf-8",

    ) as f:

        feature_columns = json.load(f)

    log(
        "Model OK"
    )

    print()

    return (

        model,

        feature_columns,

    )


# ===========================================================
# 予測データ作成
# ===========================================================

def build_prediction_dataset(

    df,

    feature_columns,

):

    log(
        "======================================="
    )

    log(
        "Feature Check"
    )

    log(
        "======================================="
    )

    # --------------------------------------------------
    # 不足列
    # --------------------------------------------------

    missing_columns = [

        c

        for c in feature_columns

        if c not in df.columns

    ]


    # --------------------------------------------------
    # 余分列
    # --------------------------------------------------

    extra_columns = [

        c

        for c in df.columns

        if c not in feature_columns

    ]


    print()

    log(
        f"学習列数 : {len(feature_columns)}"
    )

    log(
        f"予測列数 : {len(df.columns)}"
    )

    print()

    log(
        f"不足列 : {len(missing_columns)}"
    )

    log(
        f"余分列 : {len(extra_columns)}"
    )

    print()


    # --------------------------------------------------
    # 不足列があれば停止
    # --------------------------------------------------

    if missing_columns:

        print(
            "===== Missing Columns ====="
        )

        for col in missing_columns:

            print(col)

        raise ValueError(
            "不足列があります"
        )


    print(
        "Feature Check OK"
    )

    print()


    # --------------------------------------------------
    # 学習時と同じ順番
    # --------------------------------------------------

    X = df[
        feature_columns
    ].copy()


    # --------------------------------------------------
    # category
    # --------------------------------------------------

    categorical_columns = [

        "jo_name",

        "grade",

        "race_type",

        "session",

        "weekday",

        "bank_type",

        "straight_type",

    ]


    for col in categorical_columns:

        if col in X.columns:

            X[col] = X[col].astype(
                "category"
            )


    return X


# ===========================================================
# AI予測
# ===========================================================

def predict(

    model,

    X,

    df,

):

    log(
        "======================================="
    )

    log(
        "Prediction"
    )

    log(
        "======================================="
    )


    # ------------------------------
    # クラス予測
    # ------------------------------

    pred = model.predict(

        X

    )


    # ------------------------------
    # 確率
    # ------------------------------

    prob = model.predict_proba(

        X

    )


    # --------------------------------------------------
    # 元データをコピー
    # --------------------------------------------------

    result = df.copy()


    # --------------------------------------------------
    # AI予測クラス
    # --------------------------------------------------

    result["predict_class"] = pred


    # --------------------------------------------------
    # 最大確率
    # --------------------------------------------------

    result["predict_probability"] = (
        prob.max(axis=1)
    )


    # --------------------------------------------------
    # クラス名
    # --------------------------------------------------

    CLASS_NAME = {
        0: "0～1,999円",
        1: "2,000～4,999円",
        2: "5,000～9,999円",
        3: "10,000～19,999円",
        4: "20,000～29,999円",
        5: "30,000～49,999円",
        6: "50,000～99,999円",
        7: "100,000円以上",
    }


    result["AI予想"] = (

        result["predict_class"]

        .map(CLASS_NAME)

    )


    # --------------------------------------------------
    # AI確信度
    # --------------------------------------------------

    result["AI確信度"] = (

        result["predict_probability"]

        * 100

    ).round(0).astype(int).astype(str) + "%"


    # --------------------------------------------------
    # 各クラス確率
    # --------------------------------------------------

    PROB_COLUMNS = [
        "0～\n1,999",
        "2,000～\n4,999",
        "5,000～\n9,999",
        "10,000～\n19,999",
        "20,000～\n29,999",
        "30,000～\n49,999",
        "50,000～\n99,999",
        "100,000\n以上",
    ]


    for i, column in enumerate(
        PROB_COLUMNS
    ):

        result[column] = (

            prob[:, i]

            * 100

        ).round(0).astype(int).astype(str) + "%"


    log(
        f"Rows : {len(result):,}"
    )

    print()

    return result


