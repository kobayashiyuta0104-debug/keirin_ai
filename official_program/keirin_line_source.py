"""Collect official KEIRIN line predictions and emit parser-compatible HTML."""

from collections import defaultdict
from html import escape
import importlib.util
from pathlib import Path


COLLECTOR_FILE = (
    Path(__file__).resolve().parent
    / "origin_program"
    / "004_collect_historical_raw.py"
)


def _load_collector():
    spec = importlib.util.spec_from_file_location(
        "official_keirin_collector",
        COLLECTOR_FILE,
    )
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot load official collector: {COLLECTOR_FILE}")

    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _venue_code(venue):
    code = venue.get("venue_code")
    if code not in (None, ""):
        return str(code).zfill(2)

    jsj001 = venue.get("jsj001")
    c0201 = jsj001.get("C0201data", {}) if isinstance(jsj001, dict) else {}
    code = c0201.get("selKjyoCd") or c0201.get("selKeirinjyoCd")
    if code not in (None, ""):
        return str(code).zfill(2)

    raise ValueError(f"Venue code missing for {venue.get('venue')!r}")


def _line_groups(narabiyoso):
    """Group shaban rows into lines using the gaps in JSJ005 ichi values."""
    if not isinstance(narabiyoso, dict):
        return []

    rows = narabiyoso.get("shaban")
    if not isinstance(rows, list):
        return []

    positions = []
    seen_cars = set()
    for row in rows:
        if not isinstance(row, dict):
            continue
        try:
            ichi = int(row.get("ichi"))
            shaban = int(row.get("shaban"))
        except (TypeError, ValueError):
            continue
        if ichi < 1 or not 1 <= shaban <= 9:
            continue
        if shaban in seen_cars:
            raise ValueError(f"Duplicate car number in JSJ005 line data: {shaban}")
        seen_cars.add(shaban)
        positions.append({"ichi": ichi, "shaban": shaban})

    positions.sort(key=lambda item: (item["ichi"], item["shaban"]))

    groups = []
    current = []
    previous_ichi = None
    for item in positions:
        ichi = item["ichi"]
        if current and previous_ichi is not None and ichi > previous_ichi + 1:
            groups.append(current)
            current = []
        current.append(item)
        previous_ichi = ichi

    if current:
        groups.append(current)
    return groups


def _render_line_html(venue_name, narabiyoso):
    groups = _line_groups(narabiyoso)
    chunks = []

    for line_index, group in enumerate(groups):
        riders_by_position = defaultdict(list)
        for item in group:
            riders_by_position[item["ichi"]].append(item["shaban"])

        for ichi in sorted(riders_by_position):
            riders = sorted(riders_by_position[ichi])
            is_seri = len(riders) > 1
            if is_seri:
                chunks.append('<li><span class="no0">(</span></li>')

            for shaban in riders:
                chunks.append(
                    f'<li><span class="no{shaban}">{shaban}</span></li>'
                )

            if is_seri:
                chunks.append('<li><span class="no0">)</span></li>')

        if line_index < len(groups) - 1:
            chunks.append('<li><span class="no0">&nbsp;</span></li>')

    return (
        f"<html><body><h2>{escape(str(venue_name))}競輪場</h2>"
        '<ul class="keirinRyosouline">'
        + "".join(chunks)
        + "</ul></body></html>"
    ), groups


def collect_lines_html(target_date, output_file, generated_by, allow_empty=False):
    """Fetch JSJ005 line data and save the legacy RACE_KEY HTML envelope.

    The generated HTML retains the markers and line-list DOM consumed by
    010_extract_historical_lines.py. The line source is Keirin.jp, so this
    pipeline no longer depends on OddsPark's calendar endpoint.
    """
    collector = _load_collector()
    daily_map = collector.build_daily_race_map(target_date)

    problems = daily_map.get("problems", [])
    if problems:
        sample = "; ".join(
            f"{item.get('problem', 'UNKNOWN')}: {item.get('error', '')}"
            for item in problems[:5]
        )
        raise RuntimeError(
            f"Official KEIRIN race map incomplete for {target_date}: {sample}"
        )

    venues = daily_map.get("venues", [])
    race_count = sum(len(venue.get("races", [])) for venue in venues)
    if race_count == 0 and not allow_empty:
        raise RuntimeError(f"No races found for {target_date}")

    output_lines = [
        "<!-- =============================================== -->",
        f"<!-- DATE={target_date} -->",
        "<!-- SOURCE=KEIRIN.JP JSJ005 -->",
        f"<!-- GENERATED BY {generated_by} -->",
        "<!-- =============================================== -->",
        "",
    ]
    line_found_count = 0
    fetched_count = 0

    for venue in venues:
        venue_name = venue.get("venue") or ""
        jo_code = _venue_code(venue)

        for race in venue.get("races", []):
            race_no = int(race["race_no"])
            encp = race.get("encParaR")
            race_key = f"{target_date}_{jo_code}_{race_no:02d}"
            if not encp:
                raise RuntimeError(f"encParaR missing for race {race_key}")

            response = collector.get_json({"encp": encp, "type": "JSJ005"})
            if not response.get("ok"):
                raise RuntimeError(
                    f"JSJ005 request failed for {race_key}: {response.get('error')}"
                )
            fetched_count += 1

            data = response.get("data")
            narabiyoso = data.get("narabiyoso") if isinstance(data, dict) else None
            race_html, groups = _render_line_html(venue_name, narabiyoso)
            has_line = bool(groups)
            if has_line:
                line_found_count += 1

            output_lines.extend([
                f"<!-- RACE_KEY={race_key} -->",
                race_html,
                "<!-- END_RACE -->",
                "",
            ])
            print(
                f"{race_key} {venue_name} "
                f"line_found={has_line} lines={len(groups)}"
            )

    if fetched_count != race_count:
        raise RuntimeError(
            f"Race count mismatch: map={race_count}, JSJ005 fetched={fetched_count}"
        )

    output_file = Path(output_file)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    temporary_file = output_file.with_name(output_file.name + ".tmp")
    temporary_file.write_text("\n".join(output_lines), encoding="utf-8")
    temporary_file.replace(output_file)

    summary = {
        "target_date": target_date,
        "race_count": race_count,
        "fetched_count": fetched_count,
        "line_found_count": line_found_count,
        "output_file": output_file,
    }
    print(
        f"Saved {output_file}: {race_count} races, "
        f"{line_found_count} races with line data"
    )
    return summary